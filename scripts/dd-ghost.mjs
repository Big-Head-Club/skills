import { chromium } from 'playwright'
const b = await chromium.launch({ args: ["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"] })
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
const errs = []; page.on('pageerror', e => errs.push(e.message))
await page.goto('http://localhost:5240'); await page.waitForTimeout(1000)
await page.evaluate(() => { localStorage.removeItem("dd.run"); window.__noAutoPause = true; __game.startRun(false); __game.advance(3, 30); let n = 0; while (__game.run.s.phase === "wave" && n++ < 300) __game.fast(20); __game.advance(0.4, 30) })
await page.waitForTimeout(2000)
await page.click('#cards .card:nth-child(1)')
const pad = await page.evaluate(() => { const s = __game.run.s; const f = s.pads.filter(p => p.launcher == null && Math.abs(p.x) <= s.view / 2).sort((a, b) => Math.abs(a.x) - Math.abs(b.x)); return __game.toScreen(f[0].x, f[0].y) })
await page.mouse.move(pad.x + 160, pad.y - 200)
await page.evaluate(() => __game.advance(0.2, 30))
await page.screenshot({ path: '/tmp/ddv/ghost-free.png', clip: { x: Math.max(0, pad.x - 200), y: Math.max(0, pad.y - 320), width: 500, height: 380 } })
await page.mouse.move(pad.x + 25, pad.y - 30)
await page.evaluate(() => __game.advance(0.2, 30))
await page.screenshot({ path: '/tmp/ddv/ghost-snap.png', clip: { x: Math.max(0, pad.x - 200), y: Math.max(0, pad.y - 320), width: 500, height: 380 } })
const m0 = await page.evaluate(() => __game.run.s.money)
await page.mouse.click(pad.x + 25, pad.y - 30)
const m1 = await page.evaluate(() => ({ money: __game.run.s.money, n: __game.run.s.launchers.length }))
console.log(JSON.stringify({ m0, m1, errs }))
await b.close()
