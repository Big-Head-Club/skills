import { chromium } from 'playwright'
const b = await chromium.launch({ args: ["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"] })
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => m.type() === 'error' && errs.push(m.text()))
await page.goto('http://localhost:5240'); await page.waitForTimeout(1000)
await page.evaluate(() => { localStorage.removeItem("dd.run"); window.__noAutoPause = true; __game.startRun(false); __game.advance(3, 30); let n = 0; while (__game.run.s.phase === "wave" && n++ < 300) __game.fast(20); __game.advance(0.4, 30) })
await page.screenshot({ path: '/tmp/ddv/shop-income.png' })
await page.waitForTimeout(1600)
const st = await page.evaluate(() => { const s = __game.run.s; return { money: s.money, items: s.offer.items.map(x => x.id + ":" + x.price) } })
await page.screenshot({ path: '/tmp/ddv/shop.png' })
// buy the first launcher card: click it, then click a pad
const li = await page.evaluate(() => __game.run.s.offer.items.findIndex(x => x.kind === "launcher"))
await page.click(`#cards .card:nth-child(${li + 1})`)
const pad = await page.evaluate(() => { const s = __game.run.s; const f = s.pads.filter(p => p.launcher == null && Math.abs(p.x) <= s.view / 2).sort((a, b) => Math.abs(a.x) - Math.abs(b.x)); return __game.toScreen(f[0].x, f[0].y) })
await page.mouse.click(pad.x, pad.y - 4)
await page.evaluate(() => __game.advance(0.3, 30))
const after = await page.evaluate(() => { const s = __game.run.s; return { money: s.money, bought: s.offer?.bought, launchers: s.launchers.map(L => L.type) } })
await page.screenshot({ path: '/tmp/ddv/shop-after.png' })
await page.click('#oGo')
await page.evaluate(() => __game.advance(0.3, 30))
const phase = await page.evaluate(() => __game.run.s.phase)
console.log(JSON.stringify({ st, after, phase, errs }))
await b.close()
