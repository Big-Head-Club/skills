import { chromium } from 'playwright'
const b = await chromium.launch({ args: ["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"] })
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => m.type() === 'error' && errs.push(m.text()))
await page.goto('http://localhost:5240'); await page.waitForTimeout(1000)
await page.evaluate(() => { localStorage.removeItem("dd.run"); window.__noAutoPause = true; __game.startRun(false); __game.advance(3, 30) })
await page.waitForTimeout(700)
await page.mouse.move(700, 300); await page.mouse.click(700, 300)
await page.evaluate(() => __game.advance(2, 30)); await page.mouse.move(701, 300)
await page.screenshot({ path: '/tmp/ddv/m-pie.png', clip: { x: 560, y: 160, width: 280, height: 280 } })
const noMeter = await page.evaluate(() => !document.getElementById("strike"))
// a strike upgrade: pick the card, tap the home city
const r = await page.evaluate(() => { const s = __game.run.s; let n = 0; while (s.phase === "wave" && n++ < 300) __game.fast(20); __game.advance(0.4, 30); s.money = 5000; s.offer.items[3] = { kind: "upgrade", id: "radius", price: 450 }; __game.offer(); return __game.toScreen(s.cities[0].x, s.cities[0].y) })
await page.waitForTimeout(600)
await page.click('#cards .card:nth-child(4)')
await page.evaluate(() => __game.advance(0.2, 30))
await page.screenshot({ path: '/tmp/ddv/m-city.png', clip: { x: Math.max(0, r.x - 200), y: Math.max(0, r.y - 240), width: 400, height: 300 } })
await page.mouse.click(r.x, r.y - 30)
await page.evaluate(() => __game.advance(0.2, 30))
const after = await page.evaluate(() => ({ ups: __game.run.s.strike.ups, money: __game.run.s.money }))
await page.screenshot({ path: '/tmp/ddv/m-city2.png', clip: { x: Math.max(0, r.x - 200), y: Math.max(0, r.y - 240), width: 400, height: 300 } })
console.log(JSON.stringify({ noMeter, after, errs }))
await b.close()
